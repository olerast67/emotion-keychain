// Хранение во флеше nRF52840: рост, знакомые и настройки одной записью.
//
// Не через файловую систему: LittleFS ядра Adafruit пишет через кэш на одну страницу
// 4 КБ, и каждое сохранение файла стирало её по шесть раз, а пропажа питания во время
// стирания портила каталог целиком. Здесь — журнал в трёх своих страницах
// 0xEA000–0xECFFF: их резервирует загрузчик (10 страниц под данные, из них LittleFS
// берёт верхние 7), и обновление прошивки их не трогает.
//
// Запись дописывается в конец текущей страницы; стирается только следующая страница,
// когда текущая заполнится, — в ней лежат лишь старые копии. Каждая запись с номером
// и контрольной суммой: при загрузке берётся самая новая целая, а оборванная пропажей
// питания просто не читается.
#pragma once

#include <stddef.h>
#include <stdint.h>

namespace storage {

constexpr size_t kMaxRecord = 512;

// Найти последнюю запись. Вызывать до радио и после него — без разницы.
void begin();
// Последняя целая запись размера n: true и данные в buf.
bool load(void* buf, size_t n);
// Последняя целая запись любого размера: копирует до cap байт, возвращает её длину или −1.
int load_any(void* buf, size_t cap);
// Дописать новую запись (n ≤ kMaxRecord). Обычно — одна запись страницы, без стирания.
bool save(const void* data, size_t n);
// Записи старой прошивки (файлы LittleFS): число байт или −1.
int legacy_load(const char* name, void* buf, size_t cap);
// Сколько стираний страниц было с включения (для консоли).
uint32_t erases();

}  // namespace storage
