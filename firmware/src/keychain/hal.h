// Железо платы, кроме датчиков I2C: питание и заряд, пищалка, вибромотор, микрофон,
// сторожевой таймер и выключение.
#pragma once

#include <Arduino.h>

namespace hal {

// Первый запуск: 3.3 В с регулятора REG0 модуля (по умолчанию он даёт 1.8 В) и
// DC/DC для ядра. Если 3.3 В ещё не записаны — записывает и перезагружает плату.
void power_init();
// Короткая перезагрузка (сторожевой таймер, программный сброс, зависание): часы шли и до неё.
// После полного выключения, подключения USB к спящей плате или первой подачи питания — false.
bool warm_reset();

// Напряжение питания системы (VDDH): без USB это ячейка, от USB — само USB.
float vsys_volts();
bool usb_present();
bool charging();  // зарядник заряжает (статус MCP73832)
// Разрешить заряд ячейки (ножка CHG_EN, нижний конец R3). По умолчанию — запрещён.
void charge_enable(bool on);
float temperature_c();
// Кварц 64 МГц, пока подключён USB: звать на каждом проходе с тем, есть ли USB (запрос и отказ
// повторяются без вреда). wait — дождаться, пока кварц пойдёт (при подключении, до 2 мс).
void usb_crystal(bool on, bool wait);
// Смещение нуля АЦП уходит с температурой: калибровать заново, если кристалл с прошлой
// калибровки нагрелся или остыл больше чем на 10 °C. Звать с каждым замером температуры.
void adc_follow_temperature(float t);

// Сторожевой таймер: 8 с; считает и во сне процессора. Загрузчик тоже его кормит.
void watchdog_start();
void watchdog_feed();
// Освободить шину I2C, если ведомый держит SDA или SCL (до Wire.begin). true — шина свободна:
// обе линии в единице и не замкнуты между собой. false — обмен по ней в ядре завис бы или не
// дошёл до ведомых: Wire на ней не запускать.
bool i2c_recover(uint8_t sda, uint8_t scl);
// Шина на 390 кГц вместо 400 (errata 219), после setClock: 0 — Wire, 1 — Wire1.
void i2c_390k(int bus);

// Выключение: всё гаснет, плата просыпается от кнопки или USB (с перезагрузкой). Сначала
// ждёт, пока отпустят кнопку (не дольше 10 с). Если к этому моменту есть USB, гасит экран,
// мотор и микрофон и возвращается: полный сон на USB не годится, кнопка при USB включает
// загрузчик (см. off_on_usb в main.cpp). Wire1 здесь выключается и экран обесточен: после
// возврата к экрану — только через новый запуск (Wire1.begin), команда по выключенной шине в
// ядре ждала бы без срока.
void system_off();
// Перезагрузка в загрузчик для обновления прошивки по USB (диск KEYCHAIN и последовательный DFU).
[[noreturn]] void enter_bootloader();

// Пищалка: два вывода в противофазе через PWM3. hz = 0 — тишина; soft — тихо (один вывод,
// узкий импульс).
void buzzer_begin();
void buzzer(uint16_t hz, bool soft);

// Вибромотор: короткие узоры без задержек. Узор — длительности «вкл, выкл, вкл…» в мс.
void vibro_begin();
void vibrate(const uint16_t* pattern, int n);
void vibro_update(uint32_t now_ms);
bool vibro_busy();
void vibro_stop();

// Микрофон PDM: уровень звука в дБ относительно полной шкалы по блокам ~32 мс.
bool mic_begin();
void mic_end();
bool mic_on();
// Новый уровень с прошлого вызова: true и значение в *dbfs.
bool mic_take(float* dbfs);

}  // namespace hal
