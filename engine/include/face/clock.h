// Время движка — миллисекунды в uint32_t, как millis(). Счётчик переполняется
// раз в 49.7 суток, поэтому моменты сравниваются только через знаковую разность,
// а любое событие планируется не дальше 2^31 мс вперёд. Так работают движок,
// поведение и прошивка.
#pragma once

#include <stdint.h>

namespace face {

// Наступил ли момент t. Верно по обе стороны переполнения, пока t не дальше 2^31 мс.
inline bool time_reached(uint32_t now, uint32_t t) { return (int32_t)(now - t) >= 0; }
// Сколько мс осталось до t; 0 — момент уже наступил.
inline uint32_t time_left(uint32_t now, uint32_t t) { return time_reached(now, t) ? 0u : t - now; }

// Дальше этого движок и поведение не спят: проснуться раз в минуту почти ничего
// не стоит, зато расписание всегда близко и «никогда» не нужно выражать числом.
constexpr uint32_t kMaxSleepMs = 60000;
// Пробуждения, которые выпадают ближе этого друг к другу, сливаются в одно.
constexpr uint32_t kWakeMergeMs = 20;

}  // namespace face
