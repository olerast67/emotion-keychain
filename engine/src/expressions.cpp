const Expression& expression(Expr e) {
  int i = (int)e;
  if (i < 0 || i >= kExprCount) i = 0;
  return kExpressions[i];
}

const char* expr_id(Expr e) { return (int)e < kExprCount ? kExprIds[(int)e] : "?"; }

const char* expr_name(Expr e, Lang l) {
  const Expression& x = expression(e);
  return pick_lang(l, x.name, x.name_en);
}
const char* expr_name(Expr e) { return expr_name(e, lang()); }
const char* expr_when(Expr e, Lang l) {
  const Expression& x = expression(e);
  return pick_lang(l, x.when, x.when_en);
}
const char* expr_when(Expr e) { return expr_when(e, lang()); }

const char* category_name(Category c, Lang l) {
  const bool en = l == Lang::En;
  switch (c) {
    case Category::Positive: return en ? "Positive" : "Позитивные";
    case Category::Negative: return en ? "Negative" : "Негативные";
    case Category::Surprise: return en ? "Surprise and fear" : "Удивление и страх";
    case Category::Cognitive: return en ? "Thoughts and attention" : "Мысли и внимание";
    case Category::Social: return en ? "Social" : "Общение";
    case Category::State: return en ? "States" : "Состояния";
    case Category::System: return en ? "System" : "Система";
    case Category::Fun: return en ? "Fun" : "Веселье";
    case Category::Meme: return en ? "Memes" : "Мемы";
    case Category::Sensor: return en ? "Sensor reactions" : "Реакции на датчики";
    default: return "?";
  }
}
const char* category_name(Category c) { return category_name(c, lang()); }

bool expr_from_id(const char* id, Expr* out) {
  for (int i = 0; i < kExprCount; ++i) {
    if (str_eq(kExprIds[i], id)) {
      *out = (Expr)i;
      return true;
    }
  }
  return false;
}

void expression_face(Expr e, Face* out) {
  const Expression& x = expression(e);
  Face f;
  f.eye[0] = x.eyes.l;
  f.eye[1] = x.eyes.r;
  f.brow[0] = x.brows.l;
  f.brow[1] = x.brows.r;
  f.mouth = x.mouth;
  f.layout = x.lay;
  *out = f;
}

