def _module_pins():
    pins = {p: "GND" for p in MDBT50Q_PADS["GND"]}
    pins.update({
        MDBT50Q_PADS["VDD"]: "VDD",      # выход REG0 3.3 В (UICR.REGOUT0 = 3V3)
        MDBT50Q_PADS["VDDH"]: "VSYS",    # питание от батареи или USB, 2.5–5.5 В
        MDBT50Q_PADS["VBUS"]: "VBUS",    # USB-детектор и USB-регулятор
        MDBT50Q_PADS["D-"]: "USB_DN",
        MDBT50Q_PADS["D+"]: "USB_DP",
        MDBT50Q_PADS["SWDIO"]: "SWDIO",
        MDBT50Q_PADS["SWDCLK"]: "SWDCLK",
    })
    for net, pin in GPIO.items():
        pins[MDBT50Q_PADS[pin]] = net
    return pins


