def P(ref, sym_fp, value, pins, lcsc=None, mpn=None, note="", dnp=False, group="", pads=None):
    """pins — выводы символа и одноимённые площадки; pads — площадки, которых нет у символа."""
    lc, mp, st = LCSC.get(value, ("", "", ""))
    return {
        "ref": ref, "symbol": sym_fp[0], "footprint": sym_fp[1], "value": value, "pins": pins, "pads": pads or {},
        "lcsc": lcsc if lcsc is not None else lc, "mpn": mpn if mpn is not None else mp,
        "status": note or st, "dnp": dnp, "group": group,
    }


